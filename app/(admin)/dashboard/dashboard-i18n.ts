/** Merged, fully-resolved dictionary type (every key is non-optional). */
export type DashStrings = typeof EN;

/**
 * Returns the dashboard string dictionary for the active language. Nested
 * groups (service/stage/txType/tile) are merged per-language too, so a missing
 * HY/RU sub-key falls back to its EN value.
 */
export function dashStrings(lang: string): DashStrings {
  const overlay = lang === "hy" ? HY : lang === "ru" ? RU : null;
  if (!overlay) return { ...EN };
  return {
    ...EN,
    ...overlay,
    service: { ...EN.service, ...(overlay.service as Record<string, string> | undefined) },
    stage: { ...EN.stage, ...(overlay.stage as Record<string, string> | undefined) },
    txType: { ...EN.txType, ...(overlay.txType as Record<string, string> | undefined) },
    tile: { ...EN.tile, ...(overlay.tile as Record<string, string> | undefined) },
  } as DashStrings;
}
